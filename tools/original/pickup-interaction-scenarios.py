def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def challenge_xml(items, card):
    """Base challenges.xml with Challenge 1 replaced by the sandbox row."""
    text = (BASE / 'challenges.xml').read_text()
    root = ET.fromstring(text)
    row = next(node for node in root if node.tag == 'challenge' and node.get('id') == '1')
    old = ET.tostring(row, encoding='unicode').strip()
    start = text.index('<challenge name="Pitch Black" id="1"')
    end = text.index('/>', start) + 2
    attributes = [('name', 'Sandbox'), ('id', '1')]
    if items:
        attributes.append(('startingitems', ','.join(map(str, items))))
    if card:
        attributes.append(('startingcard', str(card)))
    # Remove every curse (the source item-only view's filter) and keep all rooms.
    attributes += [('endstage', '6'), ('cursefilter', '127')]
    replacement = '<challenge ' + ' '.join(f'{key}="{value}"' for key, value in attributes) + ' />'
    result = text[:start] + replacement + text[end:]
    parsed = ET.fromstring(result)
    if [node.get('id') for node in parsed] != [node.get('id') for node in root]:
        raise ValueError('Sandbox rewrite changed the Challenge rows')
    return result, old


def main():
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--count', type=int, default=1, help='Fresh OS boot epochs per run (0..8)')
    parser.add_argument('--only', action='append', default=[])
    args = parser.parse_args()
    if not 0 <= args.count <= 8:
        parser.error('--count must be 0..8')
    unknown = sorted(set(args.only) - set(CASES))
    if unknown:
        parser.error(f'Unknown case(s) {unknown}; known: {sorted(CASES)}')
    rooms_codec = load('interaction_room_codec', ROOT / 'tools/foundation/decode-rooms.py')
    stb_path = BASE / 'rooms/00.special rooms.stb'
    stb_raw = stb_path.read_bytes()
    rooms = rooms_codec.decode_bytes(stb_raw, source=str(stb_path))
    room = rooms[START_ROOM]
    if (room['type'], room['variant'], room['width'], room['height']) != (1, 2, 13, 7):
        raise ValueError('Sandbox requires the base Start Room record')
    base_spawns = copy.deepcopy(room['spawns'])
    base_doors = copy.deepcopy(room['doors'])
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    resources = output / 'resources'
    resources.mkdir()
    names = args.only or list(CASES)
    epochs = [('fixed', 1700000000, 0)]
    with (output / 'os-entropy.jsonl').open('x') as journal:
        for index in range(args.count):
            raw = os.urandom(4)
            epoch = int.from_bytes(raw, 'little')
            journal.write(json.dumps(dict(rawHex=raw.hex(), bootEpochSeed=epoch)) + '\n')
            epochs.append((f'random-{index}', epoch, (epoch >> 31) & 1))
    cases = []
    for name in names:
        spec = CASES[name]
        xml, _ = challenge_xml(spec['items'], spec['card'])
        xml_path = resources / f'{name}-challenges.xml'
        xml_path.write_text(xml)
        room['spawns'] = base_spawns + copy.deepcopy(spec['spawns'])
        if spec.get('room') == '2x2':
            # The original admits a 26x14 Start Room record as the run's
            # first room (Isaac still enters at world 320,400).
            room['width'], room['height'] = 26, 14
            room['doors'] = DOORS_2X2
            room['spawns'] = copy.deepcopy(spec['spawns'])
        stb = rooms_codec.encode_bytes(rooms)
        stb_file = resources / f'{name}-special.stb'
        stb_file.write_bytes(stb)
        for suffix, epoch, phase in epochs:
            cases.append(dict(
                name=f'{name}-{suffix}', interaction=name, about=spec['about'],
                bootEpochSeed=epoch, initialPhaseOffset=phase,
                fixture=dict(kind='sandbox-challenge-start-room', challengeId=1,
                             startingItems=spec['items'], startingCard=spec['card'],
                             startRoomSpawns=copy.deepcopy(spec['spawns']), startRoomShape=spec.get('room', '1x1'),
                             authoredResourcePath=str(xml_path.relative_to(output)),
                             specialRoomsPath=str(stb_file.relative_to(output)),
                             specialRoomsSha256=hashlib.sha256(stb).hexdigest()),
                actions=copy.deepcopy(spec['actions']), interactions=list(spec['interactions'])))
        room.update(width=13, height=7, doors=base_doors)
    room['spawns'] = base_spawns
    if rooms_codec.encode_bytes(rooms) != stb_raw:
        raise ValueError('Room codec must round-trip the base catalogue')
    (output / 'scenarios.json').write_text(json.dumps(dict(schema=1, suite='pickup-interactions', cases=cases), indent=2) + '\n')
    print(json.dumps(dict(status='declared-not-executed', cases=len(cases), output=str(output))))


if __name__ == '__main__':
    main()
