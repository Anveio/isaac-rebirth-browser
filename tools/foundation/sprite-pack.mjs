// The shipped sprite pack: every sheet an animation the page can play
// references. The page's animation catalogues (the *-data.json files web/*.ts
// imports, committed and build-time generated) name each actor's sheets. A
// sheet missing from the pack throws at draw time and stops the game (#912), so
// the pack is generated from those references instead of listed by hand.
//
//   node tools/foundation/sprite-pack.mjs           check every reference resolves
//   node tools/foundation/sprite-pack.mjs --write   also write web/generated/sprite-pack.ts
//
// The check fails when a referenced sheet is absent from the local resources.
// The renderer draws only actors from these catalogues, so with every one of
// their sheets packed a draw cannot miss its image. The generated
// module imports each sheet by URL, so Vite emits exactly those files; the
// resources themselves are read at build time and never copied into the repo.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const WEB = join(ROOT, 'web');
const RESOURCES = join(ROOT, 'references/isaac/rebirth/resources');
const OUTPUT = join(WEB, 'generated/sprite-pack.ts');

// Same rule as normalizeAssetPath in web/animation.ts.
const normalize = path => path.replaceAll('\\', '/').split('/').reduce((parts, part) => {
  if (part === '..') parts.pop(); else if (part !== '.' && part !== '') parts.push(part);
  return parts;
}, []).join('/').replace(/^resources\//i, '').toLowerCase();

function files(directory, found = new Map()) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files(path, found);
    else if (entry.isFile()) found.set(normalize(relative(RESOURCES, path)), path);
  }
  return found;
}

const sources = readdirSync(WEB).filter(name => name.endsWith('.ts')).map(name => join(WEB, name));
const catalogues = [...new Set(sources.flatMap(file => [...readFileSync(file, 'utf8')
  .matchAll(/from\s+["'](\.\/[^"']+\.json)["']/g)].map(match => resolve(WEB, match[1]))))].sort();
const onDisk = files(RESOURCES);
const sheets = new Map();
let actors = 0;
const problems = [];
for (const file of catalogues) {
  if (!existsSync(file)) {
    problems.push(`${relative(ROOT, file)} is imported by web/ but absent; run npm run assets:minimap and assets:unlock-notifications`);
    continue;
  }
  const data = JSON.parse(readFileSync(file, 'utf8'));
  if (!data || typeof data !== 'object' || Array.isArray(data)) continue;
  for (const [name, actor] of Object.entries(data)) {
    if (!actor || !Array.isArray(actor.Spritesheets) || typeof actor.BaseSpritesheetPath !== 'string') continue;
    actors++;
    for (const sheet of actor.Spritesheets) {
      const path = normalize(`${actor.BaseSpritesheetPath}/${sheet.Path}`);
      const source = onDisk.get(path);
      if (source) sheets.set(path, source);
      // web/animation.ts adds these few from web/assets itself.
      else if (existsSync(join(WEB, 'assets', path.split('/').pop()))) continue;
      else problems.push(`${path} (used by ${relative(ROOT, file)}: ${name}) is not in the local resources`);
    }
  }
}
if (problems.length) {
  for (const problem of [...new Set(problems)].sort()) console.error(problem);
  console.error(`Sprite pack: ${problems.length} unresolved references`);
  process.exit(1);
}
if (process.argv.includes('--write')) {
  const entries = [...sheets].sort(([a], [b]) => a.localeCompare(b));
  const lines = ['// Generated by tools/foundation/sprite-pack.mjs; do not edit.'];
  entries.forEach(([, source], index) => lines.push(`import sheet${index} from ${JSON.stringify(relative(dirname(OUTPUT), source).split('\\').join('/') + '?url')};`));
  lines.push('const sheets: Record<string, string> = {');
  entries.forEach(([path], index) => lines.push(`  ${JSON.stringify(path)}: sheet${index},`));
  lines.push('};', 'export default sheets;', '');
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, lines.join('\n'));
}
console.log(`Sprite pack: ${sheets.size} sheets for ${actors} animations from ${catalogues.length} catalogues`);
