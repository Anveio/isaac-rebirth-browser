import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { discoverNodeCases, discoverTestCases, NODE_TEST_GLOB } from "./scenario-index.mjs";

test("source discovery reflects added/deleted scenarios and rejects disabled or undocumented registrations", (t) => {
  const root = mkdtempSync(join(tmpdir(), "isaac-scenario-index-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const directory = join(root, "tools/foundation");
  mkdirSync(directory, { recursive: true });
  writeFileSync(join(root, "package.json"), JSON.stringify({ scripts: { "test:verification": `node --test ${NODE_TEST_GLOB}` } }));
  const source = join(directory, "fixture.test.mjs");
  writeFileSync(source, 'test("movement", () => {});\n');
  assert.deepEqual(discoverNodeCases({ root }).map((item) => item.name), ["movement"]);
  writeFileSync(source, 'test("movement", () => {});\ntest("shooting", () => {});\n');
  assert.deepEqual(discoverNodeCases({ root }).map((item) => item.name), ["movement", "shooting"]);
  writeFileSync(source, 'test("shooting", () => {});\n');
  assert.deepEqual(discoverNodeCases({ root }).map((item) => item.name), ["shooting"]);
  writeFileSync(source, 'test.beforeAll(async () => {});\ntest.afterEach(() => {});\ntest("shooting", () => {});\n');
  assert.deepEqual(discoverNodeCases({ root }).map((item) => item.name), ["shooting"], "Lifecycle setup does not create a scenario or omit its literal case");
  writeFileSync(source, '/*\ntest("commented out", () => {});\n*/\ntest("shooting", () => {});\n');
  assert.deepEqual(discoverNodeCases({ root }).map((item) => item.name), ["shooting"]);
  writeFileSync(source, 'test.skip("movement", () => {});\n');
  assert.throws(() => discoverNodeCases({ root }), /every scenario must execute/);
  writeFileSync(source, 'test("movement", { skip: true }, () => {});\n');
  assert.throws(() => discoverNodeCases({ root }), /every scenario must execute/);
  writeFileSync(source, 'test("movement", { todo: "later" }, () => {});\n');
  assert.throws(() => discoverNodeCases({ root }), /every scenario must execute/);
  writeFileSync(source, 'test(nameFromElsewhere, () => {});\n');
  assert.throws(() => discoverNodeCases({ root }), /Undocumented dynamic scenario/);
  writeFileSync(source, 'test("unimplemented");\n');
  assert.throws(() => discoverNodeCases({ root }), /Missing or dynamic scenario callback/);
  writeFileSync(source, 'test("movement", () => {});\ntest("movement", () => {});\n');
  assert.throws(() => discoverNodeCases({ root }), /duplicated scenario title/);
  rmSync(source);
  assert.throws(() => discoverTestCases({ root }), /No executable scenario sources/);
});
