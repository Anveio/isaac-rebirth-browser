//! Public Rebirth seed encoding, independently transcribed from the documented
//! alphabet/checksum/XOR format. No seed-specific acceptance or generation path.
//! Source: SolarPolarMan, https://gist.github.com/ChildishGiant/bf39d195dbdc9093417bc8f5b85b57e8
const ALPHABET: &[u8; 32] = b"ABCDEFGHJKLMNPQRSTWXYZ01234V6789";
const MASK: u32 = 0x0fef_7ffd;
/// Public xorshift startup stream, shift-index 27. Stage 1 is its second draw;
/// this limited routing has been checked against fresh original-game logs.
pub fn startup_next(mut value: u32) -> u32 {
    value ^= value >> 3;
    value ^= value << 23;
    value ^= value >> 25;
    value
}
pub fn stage1_seed(value: u32) -> u32 {
    startup_next(startup_next(value))
}
/// Seeds::SetStartSeed5e1470 initializes shift27, fills the twelve fields
/// at +14..40 and one field at +44. GameNewRun then asks that same owner
/// for the ItemPool initializer. No shared MT participates in this handoff.
#[derive(Clone, Debug, serde::Deserialize, serde::Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct RunSeeds {
    pub start_seed: u32,
    pub stream_state: u32,
    pub initialized_fields: [u32; 13],
    ///Actual Seeds+48/GameA1D8, independent of ChallengeID.
    ///Only a source-owned setter string admits this operand.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_effect_mode: Option<u32>,
}
impl RunSeeds {
    pub fn new(start_seed: u32) -> Result<Self, String> {
        if start_seed == 0 {
            return Err("run seed zero is reserved".into());
        }
        let mut stream_state = start_seed;
        let initialized_fields = std::array::from_fn(|_| {
            stream_state = startup_next(stream_state);
            stream_state
        });
        Ok(Self {
            start_seed,
            stream_state,
            initialized_fields,
            source_effect_mode: None,
        })
    }
    ///59D155 forwards5E1170's numeric formatter through594620,
    ///54EB20 and5E1470. Formatting and lookup consume no RNG.
    pub(crate) fn admit_formatted_seed_effect(&mut self) -> Result<(), String> {
        let mut code = encode(self.start_seed)?.into_bytes();
        code.insert(4, b' ');
        self.source_effect_mode = Some(source_seed_effect_mode(&code));
        Ok(())
    }

    pub fn item_pool_seed(&mut self) -> u32 {
        self.stream_state = startup_next(self.stream_state);
        self.stream_state
    }
}
